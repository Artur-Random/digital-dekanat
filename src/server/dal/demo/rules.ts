import type { EducationLevelCode, RuleTrigger } from "@/generated/prisma/client";

export type RuleSeed = {
  trigger: RuleTrigger;
  title: string;
  body: string;
  normCodes: string[];
  /** Только очная форма и бюджет. */
  stipendOnly: boolean;
  /** Прямой нормы нет: «так устроено в прототипе». */
  prototypeAssumption: boolean;
  levels: EducationLevelCode[];
  verified: boolean;
};

const LEVELS: EducationLevelCode[] = ["BACHELOR", "MASTER", "SPECIALIZED_MASTER", "BASIC_HE"];

/** Тексты, сверенные Кириллом 14.11.2026 (номера в rules-review.md: 1–13, 15, 16, кроме 14). */
const VERIFIED = new Set<RuleTrigger>([
  "DEBT_STAGE_1",
  "DEBT_STAGE_2",
  "DEBT_NOT_LIQUIDATED",
  "GRADE_SATISFACTORY",
  "NO_SHOW",
  "ABSENCE_NOTICE",
  "RETAKE_RAISED_STIPEND",
  "RETAKE_SCHEDULE_LOCKED",
  "CONDITIONAL_TRANSFER",
  "RETAKE_FREE",
  "ACADEMIC_LEAVE_NO_STAY",
  "STIPEND_STOPPED",
  "STIPEND_PAID",
  "RETAKE_SCHEDULE_PUBLISH",
  "GRADE_SATISFACTORY_ASSIGNMENT",
]);

function rule(
  trigger: RuleTrigger,
  title: string,
  body: string,
  normCodes: string[],
  stipendOnly = false,
  prototypeAssumption = false,
): RuleSeed {
  return {
    trigger,
    title,
    body,
    normCodes,
    stipendOnly,
    prototypeAssumption,
    levels: LEVELS,
    verified: VERIFIED.has(trigger),
  };
}

