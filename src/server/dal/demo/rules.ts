export type RuleSeed = {
  trigger: RuleTrigger;
  title: string;
  body: string;
  normCodes: string[];
  /** Только очная форма и бюджет (N-22). */
  stipendOnly: boolean;
  levels: EducationLevelCode[];
  verified: boolean;
};

const LEVELS: EducationLevelCode[] = ["BACHELOR", "MASTER", "SPECIALIZED_MASTER"];

function rule(
  trigger: RuleTrigger,
  title: string,
  body: string,
  normCodes: string[],
  stipendOnly = false,
): RuleSeed {
  return { trigger, title, body, normCodes, stipendOnly, levels: LEVELS, verified: false };
}

